import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const presetsDir = path.join(__dirname, '../lib/data/presets');
const outFile = path.join(__dirname, '../lib/data/presetSources.js');

const files = {
  FOUR_WEEK: '4-week.txt',
  NINE_WEEK: '9-week.txt',
  LIBRARY_24: '24-swim-workouts.txt',
  TEN_WEEK_SPEED: '10-week-speed.txt',
};

const exports = Object.entries(files).map(([key, filename]) => {
  const content = fs.readFileSync(path.join(presetsDir, filename), 'utf8');
  return `export const ${key} = ${JSON.stringify(content)};`;
});

fs.writeFileSync(
  outFile,
  `// Auto-generated by scripts/embed-preset-sources.mjs — do not edit\n\n${exports.join('\n\n')}\n`
);

console.log('Wrote', outFile);
